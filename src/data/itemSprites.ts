/** Resolve a catalogue ID, item name, rune name or familiar rune abbreviation. */
export function itemSprite(nameOrAlias: string): string | undefined {
  const key = nameOrAlias.toLowerCase().trim()
    .replace(/^(?:fibula:item:|rune:)/, '')
    .normalize('NFKD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, '').replace(/(?:rune){2,}$/, 'rune');
  const slug = Object.hasOwn(sprites, key) ? sprites[key] : undefined;
  return slug ? `/assets/items/${slug}.png` : undefined;
}
